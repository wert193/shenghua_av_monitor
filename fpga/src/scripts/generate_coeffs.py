"""Deterministic 255-tap Hamming FIR banks, Q1.15 scale in signed 18-bit ROM."""
from pathlib import Path
import hashlib
import json
import numpy as np

root = Path(__file__).resolve().parents[1]
k = np.arange(255)-127
window = np.hamming(255)
def lowpass(hz):
    f = hz/48000
    return 2*f*np.sinc(2*f*k)
banks = []
for h, center in [(lowpass(800), 0), ((k==0)-lowpass(3000), 24000),
                  (lowpass(2500)-lowpass(800), 1650)]:
    h = h*window
    h /= np.sum(h*np.cos(2*np.pi*center*k/48000))
    banks.append(np.rint(h*32768).astype(np.int32))
original = np.zeros(255, np.int32)
original[127] = 32768
banks.append(original)
q = np.pad(np.asarray(banks), ((0,0),(0,1)))
text = '// Generated by scripts/generate_coeffs.py; coefficient scale = 32768.\n'
text += 'static const int COEFFICIENTS[4][256] = {\n'
text += ',\n'.join('  {'+', '.join(map(str,row))+'}' for row in q)
text += '\n};\n'
(root/'hls'/'coefficients.h').write_text(text, encoding='utf-8')
(root/'reports'/'coefficients.json').write_text(json.dumps({
    'sample_rate':48000, 'taps':255, 'q_scale':32768,
    'modes':['lowpass_800','highpass_3000','bandpass_800_2500','original_delay_127'],
    'coefficients': q.tolist(), 'header_sha256':hashlib.sha256(text.encode()).hexdigest()}, indent=2))
print('Generated four coefficient banks, including delayed original.')
